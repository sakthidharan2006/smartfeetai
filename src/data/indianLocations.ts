/**
 * Fast client-side fuzzy search across Indian locations
 */
export function searchIndianLocations(query: string, limit: number = 12): IndianLocation[] {
  if (!query || query.trim().length === 0) {
    return INDIAN_LOCATIONS.slice(0, limit);
  }

  const clean = query.trim().toLowerCase();

  return INDIAN_LOCATIONS.filter((loc) => {
    // Check city name
    if (loc.name.toLowerCase().includes(clean)) return true;
    // Check state
    if (loc.state.toLowerCase().includes(clean)) return true;
    // Check display name
    if (loc.displayName.toLowerCase().includes(clean)) return true;
    // Check aliases
    return loc.aliases.some((alias) => alias.toLowerCase().includes(clean));
  }).slice(0, limit);
}

/**
 * Resolves precise coordinates for any location query string.
 * Uses exact match -> partial match -> alias match -> geographic centroid.
 */
export function findLocationCoordinates(query: string): [number, number] {
  if (!query) return [20.5937, 78.9629];
  const clean = query.trim().toLowerCase();

  // 1. Direct city or display name match
  for (const loc of INDIAN_LOCATIONS) {
    if (loc.displayName.toLowerCase() === clean) return loc.coordinates;
    if (loc.name.toLowerCase() === clean) return loc.coordinates;
  }

  // 2. Contains match
  for (const loc of INDIAN_LOCATIONS) {
    if (clean.includes(loc.name.toLowerCase())) return loc.coordinates;
    if (loc.displayName.toLowerCase().includes(clean)) return loc.coordinates;
    for (const alias of loc.aliases) {
      if (clean.includes(alias.toLowerCase())) return loc.coordinates;
    }
  }

  // 3. Fallback Central India coordinate (Nagpur Zero Mile corridor)
  return [21.1458, 79.0882];
}

